function sourceSymbol(kind: 'v' | 'i' | 'vsrc' | 'isrc', ac = false): SymbolShape[] {
  const out: SymbolShape[] = [
    { k: 'line', x1: 0, y1: -2, x2: 0, y2: -1 },
    { k: 'line', x1: 0, y1: 1, x2: 0, y2: 2 },
    { k: 'circle', cx: 0, cy: 0, r: 1 },
  ];
  if (kind === 'v') {
    out.push({ k: 'line', x1: -0.5, y1: 0, x2: 0.5, y2: 0, t: 0.14 });
    out.push({ k: 'line', x1: 0, y1: -0.5, x2: 0, y2: 0.5, t: 0.14 });
  } else if (kind === 'i') {
    out.push({ k: 'line', x1: 0, y1: 0.6, x2: 0, y2: -0.6, t: 0.14 });
    out.push({ k: 'filled', pts: [0, -0.7, 0.35, -0.1, -0.35, -0.1] });
  }
  if (ac) out.push({ k: 'arc', cx: 0, cy: 0, r: 0.55, a0: 200, a1: 340, t: 0.1 });
  return out;
}

