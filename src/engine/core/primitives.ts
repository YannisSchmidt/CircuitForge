/** Resistor body (IEC rectangle) as a reusable shape list. */
function resistorBody(w = 0.75, h = 1.5): SymbolShape[] {
  return [
    { k: 'line', x1: 0, y1: -2, x2: 0, y2: -h },
    { k: 'line', x1: 0, y1: h, x2: 0, y2: 2 },
    { k: 'rect', x: -w, y: -h, w: 2 * w, h: 2 * h, t: 0.14 },
  ];
}

